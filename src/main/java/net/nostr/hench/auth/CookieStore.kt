package net.nostr.hench.auth

import android.content.Context
import android.content.SharedPreferences
import androidx.core.content.edit
import java.io.File

/**
 * Persists and retrieves [PlatformSession] instances via SharedPreferences.
 * Also handles writing a Netscape-format cookie file for yt-dlp `--cookies`.
 */
class CookieStore(context: Context) {

    private val prefs: SharedPreferences =
        context.getSharedPreferences("platform_sessions", Context.MODE_PRIVATE)
    private val cookieDir = File(context.filesDir, "cookies")

    fun all(): List<PlatformSession> {
        return prefs.all.keys
            .filter { it.startsWith(PREFIX_SESSION_) }
            .mapNotNull { key -> deserialize(prefs.getString(key, null) ?: return@mapNotNull null) }
    }

    fun get(platform: Platform): PlatformSession? {
        return deserialize(prefs.getString(sessionKey(platform), null))
    }

    fun getForUrl(url: String): PlatformSession? {
        val platform = Platform.forUrl(url) ?: return null
        return get(platform)
    }

    fun save(session: PlatformSession) {
        prefs.edit { putString(sessionKey(session.platform), serialize(session)) }
    }

    fun remove(platform: Platform) {
        prefs.edit { remove(sessionKey(platform)) }
        cookieFileFor(platform).delete()
    }

    fun removeAll() {
        prefs.edit { clear() }
        cookieDir.deleteRecursively()
    }

    /**
     * Writes the session's cookies to a Netscape cookie file and returns the file path.
     * Returns null if no session exists for the platform or cookies are empty.
     */
    fun writeCookieFile(platform: Platform): String? {
        val session = get(platform) ?: return null
        if (session.cookiesNetscape.isBlank()) return null
        cookieDir.mkdirs()
        val file = cookieFileFor(platform)
        file.writeText(buildString {
            appendLine("# Netscape HTTP Cookie File")
            appendLine("# Generated by hench for ${platform.displayName}")
            appendLine("# Do not edit manually")
            appendLine()
            append(session.cookiesNetscape)
        })
        return file.absolutePath
    }

    /**
     * Writes all healthy sessions into a single cookie file.
     * Returns the file path, or null if no usable sessions exist.
     */
    fun writeCombinedCookieFile(): String? {
        val sessions = all().filter { it.isUsable && it.cookiesNetscape.isNotBlank() }
        if (sessions.isEmpty()) return null
        cookieDir.mkdirs()
        val file = File(cookieDir, "combined_cookies.txt")
        file.writeText(buildString {
            appendLine("# Netscape HTTP Cookie File")
            appendLine("# Generated by hench — all platforms")
            appendLine("# Do not edit manually")
            appendLine()
            sessions.forEach { session ->
                appendLine("# ${session.platform.displayName}")
                appendLine(session.cookiesNetscape)
                appendLine()
            }
        })
        return file.absolutePath
    }

    fun recordJobCompleted(platform: Platform) {
        val current = get(platform) ?: return
        save(current.withJobCompleted())
    }

    private fun cookieFileFor(platform: Platform): File =
        File(cookieDir, "${platform.name.lowercase()}_cookies.txt")

    companion object {
        private const val PREFIX_SESSION_ = "session_"

        private fun sessionKey(platform: Platform) = PREFIX_SESSION_ + platform.name

        private fun serialize(session: PlatformSession): String = buildString {
            append(session.platform.name)
            append('\u0000')
            append(session.cookiesNetscape.replace("\u0000", ""))
            append('\u0000')
            append(session.loggedInAtMs)
            append('\u0000')
            append(session.lastHealthCheckMs)
            append('\u0000')
            append(session.health.name)
            append('\u0000')
            append(session.jobsProcessed)
            append('\u0000')
            append(session.lastJobProcessedMs)
        }

        private fun deserialize(raw: String?): PlatformSession? {
            if (raw == null) return null
            val parts = raw.split('\u0000')
            if (parts.size < 7) return null
            return runCatching {
                PlatformSession(
                    platform = Platform.valueOf(parts[0]),
                    cookiesNetscape = parts[1],
                    loggedInAtMs = parts[2].toLongOrNull() ?: 0L,
                    lastHealthCheckMs = parts[3].toLongOrNull() ?: 0L,
                    health = runCatching { SessionHealth.valueOf(parts[4]) }.getOrDefault(SessionHealth.UNKNOWN),
                    jobsProcessed = parts[5].toIntOrNull() ?: 0,
                    lastJobProcessedMs = parts[6].toLongOrNull() ?: 0L,
                )
            }.getOrNull()
        }
    }
}
